// Debug builds trust user-installed CAs; release builds trust the system store plus
// any CA certificates committed to mobile/certs/ (see below).
//
// The owner's homelab serves Matka (and Metro, during development) with
// certificates from a private Caddy CA installed on the phone as a *user* CA,
// which Android apps ignore unless their network security config opts in.
// Opting in for every build would let anyone who can get a CA onto the phone
// (MDM, a "VPN" app, a shared device) intercept the device token, so only the
// debug variant does it:
//
//   app/src/main/res/xml/network_security_config.xml   system CAs, no cleartext   (release)
//   app/src/debug/res/xml/network_security_config.xml  system + user CAs, cleartext allowed (debug)
//   app/src/debugOptimized/res/xml/…                   same as debug
//
// Private CAs in release builds (build-time setting): every *.crt / *.pem in
// mobile/certs/ is bundled and trusted in addition to the system store, and nothing
// else is. Self-hosters behind a private CA (the owner's homelab: Caddy's local root)
// commit that one root certificate there; builds without it stay system-only. This
// pins trust to that specific CA instead of opting in to every user-installed one.
//
// Android merges the build type's source set over main, so in debug builds the same
// @xml/network_security_config resolves to the debug file there. Cleartext stays
// allowed in debug as before (Metro over LAN, http://localhost servers); with a
// network security config present, Android ignores android:usesCleartextTraffic,
// so it has to be stated here.
const fs = require("fs");
const path = require("path");
const { withAndroidManifest, withDangerousMod } = require("expo/config-plugins");

const CERTS_DIR = path.join(__dirname, "..", "certs");

/** Bundled CA files: [raw resource name, file path]. */
function bundledCAs() {
  if (!fs.existsSync(CERTS_DIR)) return [];
  return fs
    .readdirSync(CERTS_DIR)
    .filter((f) => /\.(crt|pem)$/i.test(f))
    .sort()
    .map((f, i) => [`matka_ca_${i}`, path.join(CERTS_DIR, f)]);
}

const releaseXml = (cas) => `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/withUserCerts.js. Release: system CAs${cas.length ? " + bundled CAs from mobile/certs" : " only"}. -->
<network-security-config>
  <base-config cleartextTrafficPermitted="false">
    <trust-anchors>
      <certificates src="system" />
${cas.map(([name]) => `      <certificates src="@raw/${name}" />`).join("\n")}
    </trust-anchors>
  </base-config>
</network-security-config>
`;

const DEBUG_XML = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/withUserCerts.js. Debug only: also trusts user-installed CAs. -->
<network-security-config>
  <base-config cleartextTrafficPermitted="true">
    <trust-anchors>
      <certificates src="system" />
      <certificates src="user" />
    </trust-anchors>
  </base-config>
</network-security-config>
`;

function write(root, sourceSet, xml) {
  const dir = path.join(root, "app/src", sourceSet, "res/xml");
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(path.join(dir, "network_security_config.xml"), xml);
}

module.exports = function withUserCerts(config) {
  config = withDangerousMod(config, [
    "android",
    async (cfg) => {
      const root = cfg.modRequest.platformProjectRoot;
      const cas = bundledCAs();
      const raw = path.join(root, "app/src/main/res/raw");
      fs.mkdirSync(raw, { recursive: true });
      for (const [name, file] of cas) {
        const pem = fs.readFileSync(file, "utf8");
        if (!pem.includes("BEGIN CERTIFICATE")) throw new Error(`${file} is not a PEM certificate`);
        fs.writeFileSync(path.join(raw, `${name}.pem`), pem);
      }
      write(root, "main", releaseXml(cas));
      // React Native's Gradle plugin adds a second debuggable build type,
      // debugOptimized (initWith debug), with its own source set.
      write(cfg.modRequest.platformProjectRoot, "debug", DEBUG_XML);
      write(cfg.modRequest.platformProjectRoot, "debugOptimized", DEBUG_XML);
      return cfg;
    },
  ]);
  return withAndroidManifest(config, (cfg) => {
    const app = cfg.modResults.manifest.application[0];
    app.$["android:networkSecurityConfig"] = "@xml/network_security_config";
    return cfg;
  });
};
